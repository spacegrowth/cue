//! docs/dev/lock-graph.dot: the lock graph for Graphviz (`dot -Tsvg`), cycle edges in red.

use crate::graph::Model;

pub fn lock_graph_dot(model: &Model) -> String {
    let mut out = String::from("// Generated by `cargo run -p xtask -- inventory`; don't edit by hand.\ndigraph locks {\n  rankdir=LR;\n  node [shape=box];\n");
    for (a, b) in model.edges.keys() {
        let style = if model.cyclic.contains(&(a.clone(), b.clone())) { " [color=red]" } else { "" };
        out += &format!("  {} -> {}{style};\n", quoted(a), quoted(b));
    }
    out + "}\n"
}

fn quoted(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
}
